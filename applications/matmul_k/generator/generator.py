#!/usr/bin/env python3
"""
matmul_k generator: integer matrix multiplication C = A x B with the inner
(k) dimension split among W workers.

Generates, in the application folder (parent of this script by default):
  config.yaml   CTG with master and worker0 .. worker{W-1}
  matmul_k.h    Problem dimensions (N, W, KB = N/W)
  data.h        A, B and the numpy golden result C_ref
  master.c      Master task (worker ID vector + master_impl.h)
  workerX.c     One file per worker (WORKER_ID + worker_impl.h)

Usage:
  python3 generator.py --workers W --size N [--seed S]
"""

import argparse
import re
import sys
from pathlib import Path

import numpy as np

WORD = 4                # bytes per int32
INT32_MAX = 2**31 - 1


def write_file(path, content):
	with open(path, "w") as f:
		f.write(content)


def c_array(name, mat, qualifier=""):
	rows = [", ".join(str(x) for x in row) for row in mat]
	body = ",\n\t".join(rows)
	return f"{qualifier}int32_t {name}[MATMUL_N * MATMUL_N] = {{\n\t{body}\n}};\n"


def gen_config_yaml(workers):
	names = [f"worker{w}" for w in range(workers)]
	lines = ["ctg:", "  master:", "    successors:"]
	lines += [f'      - "{n}"' for n in names]
	for n in names:
		lines += [f"  {n}:", "    successors:", '      - "master"']
	return "\n".join(lines) + "\n"


def gen_matmul_h(size, workers, seed):
	return f"""/* Generated by generator/generator.py: do not edit */

#pragma once

#define MATMUL_N	{size}
#define MATMUL_W	{workers}
#define MATMUL_KB	(MATMUL_N / MATMUL_W)	/* Inner block per worker */
#define MATMUL_SEED	{seed}
"""


def gen_data_h(a, b, c, seed, value_range):
	return (
		"/* Generated by generator/generator.py: do not edit */\n"
		f"/* seed={seed}, values in [{-value_range}, {value_range}], C_ref = numpy.matmul(A, B) */\n\n"
		"#pragma once\n\n"
		"#include <stdint.h>\n\n"
		'#include "matmul_k.h"\n\n'
		+ c_array("A", a) + "\n"
		+ c_array("B", b) + "\n"
		+ c_array("C_ref", c, "const ")
	)


def gen_master_c(workers):
	ids = ", ".join(f"worker{w}" for w in range(workers))
	return f"""/* Generated by generator/generator.py: do not edit */

#include "matmul_k.h"

/* Task IDs are assigned in alphabetical order (worker10 < worker2) */
const int P[MATMUL_W] = {{{ids}}};

#include "master_impl.h"
"""


def gen_worker_c(w):
	return f"""/* Generated by generator/generator.py: do not edit */

#define WORKER_ID {w}

#include "worker_impl.h"
"""


def memory_report(size, workers):
	"""Estimated data footprint in bytes (static arrays only)"""
	n2 = size * size
	kb = size // workers
	master = WORD * (5 * n2 + size * kb)
	worker = WORD * (2 * size * kb + n2)
	biggest_msg = WORD * n2		# C'w, buffered in the worker kernel heap
	return master, worker, biggest_msg


def main():
	parser = argparse.ArgumentParser(description="matmul_k (inner dimension decomposition) generator")
	parser.add_argument("-w", "--workers", type=int, required=True, help="number of workers W")
	parser.add_argument("-n", "--size", type=int, required=True, help="matrix size N (N x N), divisible by W")
	parser.add_argument("-s", "--seed", type=int, default=0, help="random seed (default: 0)")
	parser.add_argument("-r", "--range", type=int, default=100, dest="value_range", help="element values in [-R, R] (default: 100)")
	parser.add_argument("-o", "--out", type=Path, default=Path(__file__).resolve().parent.parent, help="application folder (default: parent of this script)")
	args = parser.parse_args()

	if args.workers < 1:
		parser.error("--workers must be >= 1")
	if args.size < 1:
		parser.error("--size must be >= 1")
	if args.size % args.workers != 0:
		parser.error(f"N ({args.size}) must be divisible by W ({args.workers})")
	if args.value_range < 1:
		parser.error("--range must be >= 1")
	if args.size * args.value_range**2 > INT32_MAX:
		parser.error("N * R^2 overflows int32: reduce --range")

	n, w = args.size, args.workers
	out = args.out
	out.mkdir(parents=True, exist_ok=True)

	rng = np.random.default_rng(args.seed)
	a = rng.integers(-args.value_range, args.value_range, size=(n, n), endpoint=True, dtype=np.int64)
	b = rng.integers(-args.value_range, args.value_range, size=(n, n), endpoint=True, dtype=np.int64)
	c = np.matmul(a, b)
	assert np.abs(c).max() <= INT32_MAX
	a, b, c = a.astype(np.int32), b.astype(np.int32), c.astype(np.int32)

	# Remove workers left over from a previous generation with more workers
	for f in out.iterdir():
		if re.fullmatch(r"worker\d+\.c", f.name):
			f.unlink()

	write_file(out / "config.yaml", gen_config_yaml(w))
	write_file(out / "matmul_k.h", gen_matmul_h(n, w, args.seed))
	write_file(out / "data.h", gen_data_h(a, b, c, args.seed, args.value_range))
	write_file(out / "master.c", gen_master_c(w))
	for i in range(w):
		write_file(out / f"worker{i}.c", gen_worker_c(i))

	master, worker, msg = memory_report(n, w)
	print(f"Generated matmul_k with N={n}, W={w}, KB={n // w}, seed={args.seed} in {out}")
	print(f"  master static data : {master / 1024:8.1f} KB (A, B, C_ref, accumulated C, received C'w, A column block)")
	print(f"  worker static data : {worker / 1024:8.1f} KB (A block, B block, C'w)")
	print(f"  largest message    : {msg / 1024:8.1f} KB (C'w, buffered in the worker kernel heap)")
	print("  page_size_data_KB must hold the task data + stack/libc, and the kernel page must hold the largest message")


if __name__ == "__main__":
	sys.exit(main())
